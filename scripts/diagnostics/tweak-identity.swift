// Concatenate after the production IPATweakIdentity.swift, then run with swift.
// Imported binaries are never executed.
let fm = FileManager.default
let scratch = fm.temporaryDirectory.appendingPathComponent("names-" + UUID().uuidString)
try fm.createDirectory(at: scratch, withIntermediateDirectories: true)
defer { try? fm.removeItem(at: scratch) }
let first = scratch.appendingPathComponent(UUID().uuidString + ".dylib")
let second = scratch.appendingPathComponent(UUID().uuidString + ".dylib")
func put(_ value: UInt32, at: Int, in bytes: inout Data) {
    for i in 0..<4 { bytes[at+i] = UInt8(truncatingIfNeeded: value >> (i*8)) }
}
var binary = Data(repeating: 0, count: 128)
put(0xfeedfacf, at: 0, in: &binary)
put(0x0100000c, at: 4, in: &binary)
put(1, at: 16, in: &binary)
put(96, at: 20, in: &binary)
put(0xd, at: 32, in: &binary)
put(96, at: 36, in: &binary)
put(24, at: 40, in: &binary)
let installName = Data("@rpath/BHTikTokPlus.dylib\0".utf8)
binary.replaceSubrange(56..<(56+installName.count), with: installName)
try binary.write(to: first)
try binary.write(to: second)
let h1 = try IPATweakIdentity.fingerprint([first])
let h2 = try IPATweakIdentity.fingerprint([second])
precondition(h1 == h2, "UUID downloads must coalesce")
precondition(IPATweakIdentity.name(preferred: first.lastPathComponent, roots: [first], fingerprint: h1) == "BHTikTokPlus")
precondition(IPATweakIdentity.name(preferred: "TikTok Extras", roots: [first], fingerprint: h1) == "TikTok Extras")
precondition(IPATweakIdentity.cleanName(first.lastPathComponent) == nil)
precondition(IPATweakIdentity.cleanName("../../Original.dylib") == "Original")
precondition(IPATweakIdentity.cleanName("bad\nname.dylib") == nil)
precondition(IPATweakIdentity.deduplicated([h1,h2], identity: { $0 }).count == 1)
binary[100] = 9
try binary.write(to: second)
let changed = try IPATweakIdentity.fingerprint([second])
precondition(changed != h1)
precondition(IPATweakIdentity.deduplicated([h1,changed], identity: { $0 }).count == 2)
let order1 = try IPATweakIdentity.fingerprint([first,second])
let order2 = try IPATweakIdentity.fingerprint([second,first])
precondition(order1 == order2)
// Big-endian FAT header containing the same little-endian arm64 slice.
var fat = Data(repeating: 0, count: 4096)
fat.replaceSubrange(0..<8, with: [0xca,0xfe,0xba,0xbe,0,0,0,1])
fat.replaceSubrange(8..<12, with: [1,0,0,12])
fat.replaceSubrange(16..<20, with: [0,0,16,0])
fat.append(try Data(contentsOf: first))
let universal = scratch.appendingPathComponent(UUID().uuidString + ".dylib")
try fat.write(to: universal)
precondition(IPATweakIdentity.metadataName(universal) == "BHTikTokPlus")
let framework = scratch.appendingPathComponent("Example.framework")
try fm.createDirectory(at: framework, withIntermediateDirectories: true)
try binary.write(to: framework.appendingPathComponent("Example"))
try PropertyListSerialization.data(fromPropertyList: ["CFBundleDisplayName": "Real Framework"], format: .xml, options: 0).write(to: framework.appendingPathComponent("Info.plist"))
precondition(IPATweakIdentity.metadataName(framework) == "Real Framework")
let fw1 = try IPATweakIdentity.fingerprint([framework])
try Data("different resources".utf8).write(to: framework.appendingPathComponent("resource"))
let fw2 = try IPATweakIdentity.fingerprint([framework])
precondition(fw2 != fw1)
let alias = scratch.appendingPathComponent("bad.dylib")
try fm.createSymbolicLink(at: alias, withDestinationURL: first)
do {
    _ = try IPATweakIdentity.fingerprint([alias])
    preconditionFailure("symlink accepted")
} catch {}
print("Production tweak names, thin/FAT metadata, exact dedupe, distinct payloads, frameworks and symlink rejection PASS")
