import {createHash,randomBytes,randomUUID,timingSafeEqual} from 'node:crypto';
import {constants} from 'node:fs';
import {mkdir,open,unlink,lstat} from 'node:fs/promises';
import {join} from 'node:path';
import {instrumentHooks} from './instrumentation.mjs';
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const HASH=/^[0-9a-f]{64}$/;
const BUNDLE=/^[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+$/;
const hash=s=>createHash('sha256').update(s).digest('hex');
const MAX=512*1024**2;
const reply=(body,status=200)=>new Response(JSON.stringify(body),{status,headers:{'content-type':'application/json','cache-control':'no-store'}});
const fail=(s,status=422)=>{throw Object.assign(Error(s),{status});};
function strict(obj,keys){if(!obj||typeof obj!=='object'||Array.isArray(obj)||Object.keys(obj).some(k=>!keys.includes(k)))fail('unexpected_fields');}
async function boundedJSON(req,limit=210000) {
 let n=0,chunks=[];
 if(!req.body)fail('missing_body');
 const reader=req.body.getReader();
 try {
  for(;;){const {done,value}=await deadline(reader.read(),10000);if(done)break;n+=value.length;if(n>limit)fail('payload_too_large',413);chunks.push(value);}
 }catch(e){await reader.cancel().catch(()=>{});throw e;}
 try{return JSON.parse(Buffer.concat(chunks).toString('utf8'));}catch{fail('invalid_json',400);}
}
async function deadline(p,ms) {let t;try{return await Promise.race([p,new Promise((_,reject)=>{t=setTimeout(()=>reject(Object.assign(Error('upload_timeout'),{status:408})),ms);})]);}finally{clearTimeout(t);}}
function ownedSource(store,p,b) {
 if(!UUID.test(b.tweakID)||!BUNDLE.test(b.bundleID)||!HASH.test(b.sourceSHA256))fail('bad_source');
 const s=store.source(p,b);if(!s)fail('source_not_owned',403);return s;
}
function principal(p){if(!p||!UUID.test(p.user)||!UUID.test(p.device)||p.fixDeviceAuthenticated!==true)fail('device_auth_required',403);}
function constantEqual(a,b){return typeof a==='string'&&typeof b==='string'&&a.length===b.length&&timingSafeEqual(Buffer.from(a),Buffer.from(b));}
export function createStagedAdapter({store,storageRoot,portEnabled=false,blackboxEnabled=false,clock=()=>Date.now()}) {
 // No server listens here. A fresh-source production route must authenticate first.
 const capabilities=()=>({schema:1,portAvailable:portEnabled,blackboxAvailable:blackboxEnabled,
    reason:portEnabled||blackboxEnabled?null:'backend_not_installed',delivery:'fix-inbox',autoEnable:false,
    automaticRepair:false,maxIPABytes:MAX,uploads:'authenticated-stream-v1'});
 return async function handle(req,p) {
  try {
   if(req.method!=='POST')return reply({error:'method_not_allowed'},405);
   const url=new URL(req.url);
   if(url.searchParams.get('action')==='port-upload') {
    principal(p);if(!portEnabled)fail('backend_not_installed',503);
    const id=url.searchParams.get('uploadID');if(!UUID.test(id??''))fail('bad_upload');
    const row=store.upload(p,id);
    if(!row||row.expires<=clock()||row.state!=='pending')fail('upload_not_pending',409);
    if(req.headers.get('content-type')!=='application/octet-stream')fail('bad_content_type',415);
    if(req.headers.get('content-length')!==String(row.bytes))fail('length_required_or_mismatch',411);
    store.transaction(()=>{
      const result=store.db.prepare("UPDATE uploads SET state='writing' WHERE id=? AND state='pending'").run(id);
      if(result.changes!==1)fail('upload_not_pending',409);
    });
    await mkdir(storageRoot,{recursive:true,mode:0o700});
    const root=await lstat(storageRoot);
    if(!root.isDirectory()||root.isSymbolicLink()||(root.mode&0o077)!==0)fail('unsafe_storage',503);
    // UUID is generated by create action. Paths/URLs never come from request JSON.
    const path=join(storageRoot,id+'.ipa');
    let fd,reader,n=0;const digest=createHash('sha256');const start=clock();
    try {
     fd=await open(path,constants.O_WRONLY|constants.O_CREAT|constants.O_EXCL|constants.O_NOFOLLOW,0o600);
     reader=req.body?.getReader();if(!reader)fail('missing_body');
     for(;;) {
      const {done,value}=await deadline(reader.read(),10000);if(done)break;
      n+=value.length;if(n>row.bytes||n>MAX)fail('upload_too_large',413);
      if(clock()-start>300000)fail('upload_timeout',408);
      digest.update(value);
      let offset=0;
      while(offset<value.length){const r=await fd.write(value,offset,value.length-offset);if(!r.bytesWritten)fail('storage_write_failed',503);offset+=r.bytesWritten;}
     }
     if(n!==row.bytes||digest.digest('hex')!==row.hash)fail('upload_hash_or_size_mismatch');
     await fd.sync();await fd.close();fd=null;
     store.db.prepare("UPDATE uploads SET state='ready' WHERE id=?").run(id);
     return reply({uploadID:id,sha256:row.hash,bytes:n,state:'ready'});
    }catch(e) {
     if(reader)await reader.cancel().catch(()=>{});
     if(fd)await fd.close().catch(()=>{});
     await unlink(path).catch(()=>{});
     store.db.prepare("UPDATE uploads SET state='failed' WHERE id=?").run(id);
     throw e;
    }
   }
   const b=await boundedJSON(req,url.pathname.endsWith('/blackbox-report')||url.searchParams.get('action')==='blackbox-report'?2048:210000);
   if(b.action==='port-capabilities') {principal(p);return reply(capabilities());}
   if(b.action==='blackbox-report') {
    if(!blackboxEnabled)fail('backend_not_installed',503);
    // Deliberately no user/device credentials here. Capability scope is one enrollment.
    strict(b,['action','installationID','reportToken','eventID','signal','exception','version','hookIndex','hookDepth','manifestSHA256']);
    if(b.version!==2||!Number.isSafeInteger(b.hookIndex)||b.hookIndex<0||b.hookIndex>2048||
       !Number.isSafeInteger(b.hookDepth)||b.hookDepth<0||b.hookDepth>32||((b.hookIndex===0)!==(b.hookDepth===0))||!HASH.test(b.manifestSHA256??'')||
       !UUID.test(b.installationID)||!UUID.test(b.eventID)||!HASH.test(b.reportToken)||
       !Number.isSafeInteger(b.signal)||typeof b.exception!=='boolean'||
       (!b.exception&&![4,5,6,7,8,10,11,12].includes(b.signal))||
       (b.exception&&b.signal!==0))fail('bad_event');
    const event=store.transaction(()=>{
     const e=store.db.prepare('SELECT * FROM enrollments WHERE id=?').get(b.installationID);
     if(!e||e.revoked||e.expires<=clock()||!constantEqual(e.token_hash,hash(b.reportToken)))fail('invalid_report_capability',403);
     const manifest=store.db.prepare('SELECT manifest_hash,manifest FROM hook_manifests WHERE enrollment_id=?').get(e.id);
     if(!manifest||manifest.manifest_hash!==b.manifestSHA256)fail('manifest_mismatch',403);
     const activeHook=b.hookIndex?JSON.parse(manifest.manifest).hooks.find(h=>h.hookIndex===b.hookIndex):null;
     if(b.hookIndex&&!activeHook)fail('unknown_hook',422);
     const fp=hash(JSON.stringify([b.signal,b.exception,b.hookIndex]));
     const previous=store.db.prepare('SELECT * FROM events WHERE enrollment=? AND (event_id=? OR fingerprint=?)')
       .get(e.id,b.eventID,fp);
     if(previous) {
      if(previous.event_id===b.eventID&&previous.fingerprint!==fp)fail('replay_mismatch',409);
      return {duplicate:true};
     }
     if(e.report_count>=5)fail('report_limit',429);
     store.db.prepare('INSERT INTO events VALUES(?,?,?,?,?,?)').run(e.id,b.eventID,fp,b.signal,+b.exception,clock());
     store.db.prepare('UPDATE enrollments SET report_count=report_count+1 WHERE id=?').run(e.id);
     const id=randomUUID(),payload=JSON.stringify({installationID:e.id,eventID:b.eventID,signal:b.signal,exception:b.exception,hookIndex:b.hookIndex,hookDepth:b.hookDepth,manifestSHA256:b.manifestSHA256,activeHook:activeHook?{className:activeHook.className,selector:activeHook.selector,kind:activeHook.kind}:null,evidence:"active-on-interrupted-thread-not-cause",culprit:null});
     store.db.prepare("INSERT INTO jobs(id,kind,user_id,device,tweak_id,bundle_id,source_hash,payload,dedup,created) VALUES(?,?,?,?,?,?,?,?,?,?)")
       .run(id,'crash-review',e.user_id,e.device,e.tweak_id,e.bundle_id,e.source_hash,payload,hash(e.id+fp),clock());
     return {duplicate:false,id};
    });
    return reply({ok:true,...event,automaticRepair:false});
   }
   principal(p);
   if(b.action==='port-upload-create') {
    if(!portEnabled)fail('backend_not_installed',503);
    strict(b,['action','id','role','bytes','sha256']);
    if(!UUID.test(b.id)||!['old','new'].includes(b.role)||!HASH.test(b.sha256)||
       !Number.isSafeInteger(b.bytes)||b.bytes<32||b.bytes>MAX)fail('bad_upload');
    const row=store.transaction(()=>{
     const existing=store.db.prepare('SELECT * FROM uploads WHERE id=?').get(b.id);
     if(existing) {
      if(existing.user_id!==p.user||existing.device!==p.device||existing.hash!==b.sha256||existing.bytes!==b.bytes||existing.role!==b.role)fail('replay_mismatch',409);
      return existing;
     }
     const global=store.db.prepare("SELECT count(*) n FROM uploads WHERE expires>? AND state IN ('pending','writing','ready')").get(clock());
     if(global.n>=16)fail('global_upload_limit',429);
     const live=store.db.prepare("SELECT count(*) n,coalesce(sum(bytes),0) bytes FROM uploads WHERE user_id=? AND expires>? AND state IN ('pending','writing','ready')")
       .get(p.user,clock());
     if(live.n>=2||live.bytes+b.bytes>2*MAX)fail('upload_limit',429);
     store.db.prepare('INSERT INTO uploads(id,user_id,device,hash,bytes,role,expires) VALUES(?,?,?,?,?,?,?)')
       .run(b.id,p.user,p.device,b.sha256,b.bytes,b.role,clock()+3600000);
     return store.upload(p,b.id);
    });
    return reply({uploadID:row.id,uploadURL:'?action=port-upload&uploadID='+row.id,
       method:'POST',contentType:'application/octet-stream',bytes:row.bytes,expiresAt:new Date(row.expires).toISOString(),state:row.state});
   }
   if(b.action==='port-request') {
    if(!portEnabled)fail('backend_not_installed',503);
    strict(b,['action','id','tweakID','bundleID','name','sourceSHA256','consent','code','oldIPA','newIPA']);
    if(b.consent!==true)fail('explicit_consent_required');
    if(!UUID.test(b.id)||typeof b.name!=='string'||b.name.length>80)fail('bad_request');
    const source=ownedSource(store,p,b);
    if(typeof b.code!=='string'||hash(b.code)!==b.sourceSHA256||b.code!==source.code)fail('source_changed',409);
    for(const [role,item] of [['old',b.oldIPA],['new',b.newIPA]]) {
     strict(item,['uploadID','sha256']);
     if(!UUID.test(item.uploadID)||!HASH.test(item.sha256))fail('bad_upload');
     const u=store.upload(p,item.uploadID);
     if(!u||u.role!==role||u.hash!==item.sha256||u.state!=='ready'||u.expires<=clock())fail('upload_not_owned_or_ready',403);
    }
    const dedup=hash(JSON.stringify([p.user,p.device,b.tweakID,b.sourceSHA256,b.oldIPA.sha256,b.newIPA.sha256]));
    const job=store.transaction(()=>{
     const old=store.db.prepare('SELECT * FROM jobs WHERE dedup=? OR id=?').get(dedup,b.id);
     if(old){if(old.dedup!==dedup)fail('replay_mismatch',409);return old;}
     const count=store.db.prepare("SELECT count(*) n FROM jobs WHERE user_id=? AND status='queued'").get(p.user).n;
     if(count>=10)fail('queue_limit',429);
     store.db.prepare('INSERT INTO jobs(id,kind,user_id,device,tweak_id,bundle_id,source_hash,payload,dedup,created) VALUES(?,?,?,?,?,?,?,?,?,?)')
       .run(b.id,'port',p.user,p.device,b.tweakID,b.bundleID,b.sourceSHA256,JSON.stringify({oldIPA:b.oldIPA,newIPA:b.newIPA,consent:true}),dedup,clock());
     return {id:b.id,status:'queued'};
    });
    return reply({id:job.id,status:job.status,delivery:'fix-inbox',autoEnable:false,automaticRepair:false},202);
   }
   if(b.action==='port-status') {
    strict(b,['action','id']);
    if(!UUID.test(b.id))fail('bad_job');
    const job=store.db.prepare("SELECT id,status,kind,source_hash FROM jobs WHERE id=? AND user_id=? AND device=?")
      .get(b.id,p.user,p.device);
    if(!job||job.kind!=='port')fail('not_found',404);
    let unresolved=[],candidates=[];
    let receipt=null;
    if(['delivered'].includes(job.status)){
     const {readFile}=await import('node:fs/promises');
     receipt=JSON.parse(await readFile(join(storageRoot,job.id+'.receipt.json'),'utf8'));
     if(receipt.originalSourceSHA256!==job.source_hash)fail('receipt_changed',503);
    }
    if(['unresolved','ready_for_build','awaiting_review'].includes(job.status)) {
     const {readFile}=await import('node:fs/promises');
     const value=await readFile(join(storageRoot,job.id+'.plan.json'));
     if(value.length>8388608)fail('invalid_plan',503);
     const plan=JSON.parse(value.toString('utf8'));
     unresolved=plan.unresolved.slice(0,100);candidates=plan.candidates.slice(0,100);
    }
    return reply({id:job.id,status:job.status,unresolved,candidates,delivery:'fix-inbox',
      autoEnable:false,automaticRepair:job.status==='delivered'||job.status==='ready_for_build',requiresReview:job.status==='unresolved',
      originalSourceSHA256:job.source_hash,newSourceSHA256:receipt?.newSourceSHA256??null,reviewedFixReady:receipt?.reviewedFixReady??false,fixID:receipt?.fixID??null,manualEnableRequired:true});
   }
   if(b.action==='blackbox-enroll') {
    if(!blackboxEnabled)fail('backend_not_installed',503);
    strict(b,['action','consent','id','tweakID','sourceSHA256','bundleID','tweakVersion','appVersion']);
    if(b.consent!==true)fail('explicit_consent_required');
    const owned=ownedSource(store,p,b);
    let hooks;try{hooks=instrumentHooks(owned.code,b.sourceSHA256);}catch{fail('unsupported_hook_instrumentation');}
    if(!UUID.test(b.id)||![b.tweakVersion,b.appVersion].every(s=>typeof s==='string'&&/^[A-Za-z0-9._+-]{1,32}$/.test(s)))fail('bad_versions');
    const token=randomBytes(32).toString('hex'),expires=clock()+30*86400000;
    store.transaction(()=>{
     if(store.db.prepare('SELECT id FROM enrollments WHERE id=?').get(b.id))fail('already_enrolled_revoke_to_rotate',409);
     const count=store.db.prepare('SELECT count(*) n FROM enrollments WHERE user_id=? AND device=? AND expires>? AND revoked=0').get(p.user,p.device,clock()).n;
     if(count>=20)fail('enrollment_limit',429);
     store.db.prepare('INSERT INTO enrollments(id,user_id,device,tweak_id,bundle_id,source_hash,tweak_version,app_version,token_hash,expires) VALUES(?,?,?,?,?,?,?,?,?,?)')
       .run(b.id,p.user,p.device,b.tweakID,b.bundleID,b.sourceSHA256,b.tweakVersion,b.appVersion,hash(token),expires);
     store.db.prepare('INSERT INTO hook_manifests VALUES(?,?,?)').run(b.id,hooks.manifestSHA256,JSON.stringify(hooks.manifest));
    });
    return reply({manifestSHA256:hooks.manifestSHA256,hookCount:hooks.manifest.hooks.length,installationID:b.id,reportToken:token,expiresAt:new Date(expires).toISOString(),maxReports:5,automaticRepair:false});
   }
   if(b.action==='blackbox-revoke') {
    strict(b,['action','installationID']);
    if(!UUID.test(b.installationID)||!store.enrollment(p,b.installationID))fail('not_found',404);
    store.db.prepare('UPDATE enrollments SET revoked=1 WHERE id=?').run(b.installationID);
    return reply({ok:true,removeInstrumentedBuildToStopLocalRecording:true});
   }
   return reply({error:'unknown_action'},400);
  }catch(e){return reply({error:e.status?e.message:'staging_unavailable'},e.status??503);}
 };
}
