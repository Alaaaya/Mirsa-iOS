import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import http from 'node:http';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {extend,TRANSLATION,REVIEW} from './extension.mjs';
const basePath=process.env.MIRSA_RELAY_BASE_MODULE;
test('staged relay really produces signed delivery, replay, dedupe and ACK',{skip:!basePath},async()=>{
 const base=await import(pathToFileURL(basePath).href),Service=extend(base);
 const delivery=[];
 const secret='whsec_'+randomBytes(32).toString('base64');
 const {Webhook}=createRequire(basePath)('standardwebhooks');
 const service=new Service({dbPath:':memory:',token:'m'.repeat(48),hookToken:'h'.repeat(48),post:async(_url,body,headers)=>{
  const data=JSON.parse(body);assert.ok(headers['webhook-signature']);
  assert.deepEqual(new Webhook(secret).verify(body,headers),data);
  if(data.type==='verification')return {status:200,body:JSON.stringify({challenge:data.challenge})};
  delivery.push(data);return {status:200,body:'{}'};
 }});
 assert.ok(service.catalog().events.some(x=>x.name===TRANSLATION));
 await service.rpc('events/subscribe',{name:TRANSLATION,arguments:{},delivery:{mode:'webhook',url:'https://fixture.example.com/callback',secret}});
 const server=http.createServer(service.handler());await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const url='http://127.0.0.1:'+server.address().port+'/internal/translation';
 const entry={queue_id:'11111111-1111-4111-8111-111111111111',user_id:'eeeeeeee-eeee-4eee-8eee-eeeeeeeeeeee',bundle_id:'com.example.fixture',revision:'a'.repeat(64),version:1,kind:'missing'};
 const p={batch_id:'22222222-2222-4222-8222-222222222222',entries:[entry]};
 const emit=(token,payload=p)=>fetch(url,{method:'POST',headers:{authorization:'Bearer '+token,'content-type':'application/json'},body:JSON.stringify(payload)});
 try{
  assert.equal((await emit('bad')).status,401);
  assert.equal((await emit('h'.repeat(48),{...p,source:'NEVER IN EVENT'})).status,400);
  const r=await emit('h'.repeat(48));assert.equal(r.status,202);assert.equal((await r.json()).eventId,'trn_'+p.batch_id);
  await service.drain();
  assert.equal(delivery.length,1);assert.deepEqual(delivery[0].data,p);
  const replay=await emit('h'.repeat(48));assert.equal((await replay.json()).replayed,true);
  await service.drain();assert.equal(delivery.length,1);
  assert.equal((await emit('h'.repeat(48),{...p,entries:[{...entry,version:2}]})).status,400);
  assert.equal((await emit('h'.repeat(48),{...p,entries:Array(33).fill(entry)})).status,400);
  assert.equal((await emit('h'.repeat(48),{...p,entries:[entry,{...entry,kind:'review'}]})).status,400);
  assert.equal((await emit('h'.repeat(48),{...p,entries:[{...entry,version:0}]})).status,400);
  const review={batch_id:'33333333-3333-4333-8333-333333333333',entries:[{...entry,kind:'review'}]};
  assert.equal((await emit('h'.repeat(48),review)).status,202);
  let events=JSON.parse((await service.rpc('tools/call',{name:'mirsa_pending_translation_events'})).content[0].text).events;
  assert.equal(events.length,2);
  assert.equal(events[1].name,REVIEW);
  await service.rpc('tools/call',{name:'mirsa_ack_translation_event',arguments:{event_id:'trn_'+p.batch_id}});
  events=JSON.parse((await service.rpc('tools/call',{name:'mirsa_pending_translation_events'})).content[0].text).events;
  assert.equal(events.length,1);
  await service.rpc('tools/call',{name:'mirsa_ack_translation_event',arguments:{event_id:'trn_'+review.batch_id}});
  assert.equal(JSON.parse((await service.rpc('tools/call',{name:'mirsa_pending_translation_events'})).content[0].text).events.length,0);
 }finally{await new Promise(r=>server.close(r));service.db.close();}
});
